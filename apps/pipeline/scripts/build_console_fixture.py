"""
Builds apps/api/tests/fixtures/console/ws_fixture_cycle.json — the W&S fixture
cycle the console read-model tests and docs/console-read-models.md samples
are built from.

    python3 scripts/build_console_fixture.py

No network, no model. What it is made of, so nobody mistakes it for a real
cycle's rows:

  * answers   real Wiggle & Snug answers from the extraction golden set
              (tests/fixtures/extraction_golden/seed5_*), with their stored
              spans and extractions. Wiggle & Snug is Parleo's own test
              store; there is no customer data here.
  * questions catalog questions generated by generation/catalog_tiers.py
              from the W&S catalog fixture for the variant each answer
              prices. The golden rows do not store their question text, so
              the pairing of answer to question is reconstructed from the
              answer's attributed product. Brand-direct question texts are
              written for the fixture.
  * outcomes  scoring/expectation_comparator.py over the stored extraction,
              with the record's variants and the pinned wiggleandsnug.com
              DNS failure (tests/fixtures/citation_checks/).
  * Layer 1   coded mentions derived from brand_mentioned, W&S first.
  * one consumer run (aimode) recorded as no_ai_answer — synthetic, to show
              a wall-type result.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from clients.truesync_catalog import build_snapshot  # noqa: E402
from generation import catalog_tiers as ct  # noqa: E402
from scoring import expectation_comparator as cmp  # noqa: E402
from scoring import record_variants as rv  # noqa: E402
from soa_shared import expected_answers as ea  # noqa: E402
from soa_shared import surfaces  # noqa: E402

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIX = os.path.join(HERE, 'tests', 'fixtures')
OUT = os.path.join(HERE, '..', 'api', 'tests', 'fixtures', 'console', 'ws_fixture_cycle.json')
STUDY = 'ws-2b-fixture'
CYCLE = 'WS-2B-FIXTURE'
RUN_AT = '2026-10-09T15:00:00+00:00'


def load(*parts):
    with open(os.path.join(FIX, *parts)) as fh:
        return json.load(fh)


def main() -> int:
    payloads = load('wiggle_and_snug_catalog.json')
    snap = build_snapshot(payloads['catalog'], merchants=payloads['merchants'],
                          incentives=payloads['incentives'], price_history=payloads['price_history'])
    variants = rv.from_snapshot(snap)
    catalog_rows, _ = ct.build_catalog_accuracy(snap, category='Baby Care',
                                                persona='Value-Conscious Parent',
                                                study_pattern='brand_at_retail')
    by_variant = {r['source_ref']['variant_id']: r for r in catalog_rows}
    brand_rows = ct.stamp_brand_direct([
        {'query_text': 'Is Wiggle & Snug Member Rewards still available?'},
        {'query_text': 'Does Wiggle & Snug sell a Snug-Fit Trial Pack?'},
    ], snap)
    pinned = load('citation_checks', 'wiggleandsnug_com_dns_failure.json')
    dead = {pinned['domain']: {'domain': pinned['domain'], 'resolves': False, 'responds': None,
                               'detail': f"does not resolve ({pinned['resolver_error']})",
                               'checked_at': RUN_AT, 'fabricated': True}}

    plan = [
        # (query_code, question row, golden answer file, stored platform, tier)
        ('WIG_167', by_variant['bum-balm-4oz'], 'seed5_row05.json', 'gemini_grounded'),
        ('WIG_167', by_variant['bum-balm-4oz'], 'seed5_row13.json', 'chatgpt'),
        ('WIG_166', by_variant['cloud-wipes-3pack'], 'seed5_row35.json', 'gemini_grounded'),
        ('WIG_165', by_variant['snug-fit-overnight-s6'], 'seed5_row01.json', 'gemini_grounded'),
        ('WIG_154', by_variant['snug-fit-diapers-s3-small'], 'seed5_row21.json', 'chatgpt'),
        ('WIG_144', brand_rows[0], 'seed5_row10.json', 'chatgpt'),
        ('WIG_148', brand_rows[1], 'seed5_row40.json', 'gemini_grounded'),
    ]

    queries, runs, outcomes, mentions = {}, [], [], []
    run_id = 1000
    for code, question, golden_file, platform in plan:
        golden = load('extraction_golden', golden_file)
        if code not in queries:
            queries[code] = {
                'id': len(queries) + 1, 'query_code': code, 'query_text': question['query_text'],
                'category': 'Baby Care', 'stage': question.get('stage') or 'Research',
                'specificity': question.get('specificity') or 'Narrow',
                'persona': 'Value-Conscious Parent', 'status': 'Active', 'study_type': STUDY,
                'study_pattern': 'brand_at_retail', 'organization_id': 1, 'tier': question['tier'],
                'expected_answer': question['expected_answer'], 'provenance': question['provenance'],
                'source_ref': question['source_ref'],
            }
        q = queries[code]
        run_id += 1
        runs.append({'id': run_id, 'cycle_id': 1, 'query_id': q['id'], 'platform': platform,
                     'run_number': 1, 'run_at': RUN_AT, 'raw_response': golden['answer'],
                     'status': 'success', 'surface': surfaces.surface_of(platform),
                     'collector': surfaces.collector_of(platform), 'answer_status': 'answered',
                     'retrieved_sources': None, '_golden': golden_file})
        extraction = golden['as_extracted']
        verdict = cmp.compare_with_secondary(
            q['expected_answer'], extraction, source_ref=q['source_ref'],
            brand_domain=q['expected_answer'].get('domain') or snap.domain, tier=q['tier'],
            brand_facts={'brand': snap.brand, 'domain': snap.domain,
                         'tier_names': [t.get('name') for t in snap.tiers if t.get('name')],
                         'product_titles': [p.title for p in snap.products]},
            record_variants=variants, dead_domains=dead,
        )
        outcomes.append({'run_id': run_id, 'query_id': q['id'], 'cycle_id': 1, 'platform': platform,
                         'tier': q['tier'], 'expected_answer': q['expected_answer'],
                         'extraction': extraction, 'outcome': verdict.outcome,
                         'outcome_reason': verdict.reason, 'flags': verdict.flags or None,
                         'claim_results': verdict.claims or None, 'source_split': verdict.source_split,
                         'reason_code': verdict.reason_code, 'surface': surfaces.surface_of(platform),
                         'source_attribution': verdict.source_attribution,
                         'domain_cited': verdict.domain_cited})
        mentions.append({'run_id': run_id, 'entity_id': 1, 'mentioned': bool(extraction.get('brand_mentioned')),
                         'position': 1 if extraction.get('brand_mentioned') else None})

    # One consumer surface result with no AI answer, on the Bum Balm question.
    run_id += 1
    runs.append({'id': run_id, 'cycle_id': 1, 'query_id': queries['WIG_167']['id'], 'platform': 'aimode',
                 'run_number': 1, 'run_at': RUN_AT, 'raw_response': '', 'status': 'success',
                 'surface': 'consumer_ui', 'collector': 'serpapi', 'answer_status': 'no_ai_answer',
                 'retrieved_sources': None, '_golden': None})
    outcomes.append({'run_id': run_id, 'query_id': queries['WIG_167']['id'], 'cycle_id': 1,
                     'platform': 'aimode', 'tier': 'catalog_accuracy',
                     'expected_answer': queries['WIG_167']['expected_answer'],
                     'extraction': {}, 'outcome': 'absent',
                     'outcome_reason': 'the surface showed no answer (no_ai_answer); counted in '
                                       'coverage, outside accuracy',
                     'flags': None, 'claim_results': None, 'source_split': None, 'reason_code': None,
                     'surface': 'consumer_ui', 'source_attribution': None, 'domain_cited': None})

    fixture = {
        '_note': __doc__.strip().split('\n\n')[0] + ' Built by scripts/build_console_fixture.py.',
        'organizations': [
            {'id': 1, 'name': 'Parleo'},
            {'id': 10, 'name': 'Wiggle & Snug', 'truesync_tenant_slug': 'wiggle-and-snug'},
            {'id': 20, 'name': 'Brandco', 'truesync_tenant_slug': 'brandco'},
        ],
        'generation_jobs': [{
            'id': 1, 'study_type': STUDY, 'study_name': 'Wiggle & Snug 2B fixture',
            'target_count': len(queries), 'created_count': len(queries), 'status': 'complete',
            'organization_id': 1, 'customer_organization_id': 10, 'created_by': 'op@parleo.io',
            'created_at': '2026-10-08T12:00:00+00:00', 'study_pattern': 'brand_at_retail',
            'allowed_categories': ['Baby Care'], 'syndicated_merchant': 'wiggle-and-snug',
            'tier_config': {'merchant': {'slug': 'wiggle-and-snug', 'brand': snap.brand,
                                         'domain': snap.domain, 'study_brand': snap.brand}},
        }],
        'entities': [
            {'id': 1, 'name': 'Wiggle & Snug', 'slug': 'wiggle-and-snug', 'entity_type': 'brand',
             'category': 'Baby Care', 'website_url': f'https://{snap.domain}/', 'aliases': ['Wiggle and Snug']},
            {'id': 2, 'name': 'Huggies', 'slug': 'huggies', 'entity_type': 'brand',
             'category': 'Baby Care', 'website_url': 'https://www.huggies.com/', 'aliases': []},
        ],
        'cycles': [{
            'id': 1, 'cycle_code': CYCLE, 'study_type': STUDY, 'study_pattern': 'brand_at_retail',
            'status': 'complete', 'cycle_mode': 'query', 'start_date': '2026-10-09',
            'end_date': '2026-10-09', 'total_runs_planned': len(runs), 'completed_runs': len(runs),
            'platforms': ['chatgpt', 'gemini_grounded', 'aimode'], 'runs_per_query': 1,
            'organization_id': 1, 'created_at': '2026-10-09T14:55:00+00:00', 'notes': None,
            'full_loop_run_id': 33, 'reference_prices': None,
        }],
        'cycle_entities': [
            {'cycle_id': 1, 'entity_id': 1, 'comparison_code': 'M001', 'role': 'primary'},
            {'cycle_id': 1, 'entity_id': 2, 'comparison_code': 'M002', 'role': 'competitor'},
        ],
        'queries': list(queries.values()),
        'runs': runs,
        'outcomes': outcomes,
        'coded_mentions': mentions,
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w') as fh:
        json.dump(fixture, fh, indent=1, default=str)
        fh.write('\n')
    for o in outcomes:
        print(o['run_id'], o['platform'], o['tier'], o['outcome'], o['reason_code'],
              [f['flag'] for f in o['flags'] or []])
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
